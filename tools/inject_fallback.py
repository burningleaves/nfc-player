#!/usr/bin/env python3
# -*- coding: utf-8 -*-
import sys
import io

# Windows 控制台默认 GBK, 强制 UTF-8 输出避免中文乱码
for _s in ('stdout', 'stderr'):
    _f = getattr(sys, _s, None)
    if _f is not None and hasattr(_f, 'reconfigure'):
        try:
            _f.reconfigure(encoding='utf-8', errors='replace')
        except Exception:
            pass

"""
inject_fallback.py -- 把 config.json 的歌单内嵌进 index.html 作为兜底。

为什么需要:
  某些托管平台(EdgeOne Pages)如果输出目录配置不对, config.json 就 404,
  页面会完全不可用。把歌单直接写进 HTML, 即使 config.json 读不到也能播。

用法:
    python tools/inject_fallback.py           # 注入
    python tools/inject_fallback.py --check   # 只检查是否已同步
"""

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
HTML = os.path.join(ROOT, "site", "index.html")
CFG = os.path.join(ROOT, "site", "config.json")

MARK_START = "  // >>> FALLBACK_SONGS (auto-generated by inject_fallback.py)"
MARK_END = "  // <<< FALLBACK_SONGS"


def build_block(songs):
    lines = [MARK_START]
    lines.append("  var FALLBACK_SONGS = [")
    for s in songs:
        lines.append("    {")
        lines.append("      id: " + json.dumps(s.get("id", ""), ensure_ascii=False) + ",")
        lines.append("      title: " + json.dumps(s.get("title", ""), ensure_ascii=False) + ",")
        lines.append("      url: " + json.dumps(s.get("url", ""), ensure_ascii=False))
        lines.append("    },")
    lines.append("  ];")
    lines.append(MARK_END)
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if not os.path.isfile(CFG):
        print("site/config.json 不存在")
        return 1
    cfg = json.load(io.open(CFG, encoding="utf-8"))
    songs = cfg.get("songs", [])
    if not songs:
        print("config.json 里没有歌曲")
        return 1

    html = io.open(HTML, encoding="utf-8").read()
    block = build_block(songs)

    if MARK_START in html and MARK_END in html:
        new = re.sub(re.escape(MARK_START) + r".*?" + re.escape(MARK_END),
                     block.replace("\\", "\\\\"), html, flags=re.S)
    else:
        anchor = "  // ---- 解析音频源 ----"
        if anchor not in html:
            print("找不到插入锚点, 请检查 index.html")
            return 1
        new = html.replace(anchor, block + "\n\n" + anchor, 1)

    if new == html:
        print("内嵌歌单已是最新")
        return 0
    if args.check:
        print("内嵌歌单与 config.json 不一致, 跑 python tools/inject_fallback.py")
        return 1

    io.open(HTML, "w", encoding="utf-8").write(new)
    print(f"已注入 {len(songs)} 首到内嵌歌单: " +
          ", ".join(s.get("id", "?") for s in songs))
    return 0


if __name__ == "__main__":
    sys.exit(main())